void Motor_PWM_SetPhaseVoltagePU(float va, float vb, float vc)
{
  motor_pwm_set_one_phase(&htim2, TIM_CHANNEL_1, TIM_CHANNEL_2, va);
  motor_pwm_set_one_phase(&htim3, TIM_CHANNEL_1, TIM_CHANNEL_2, vb);
  /* Cube: PA8=C_L on TIM1_CH1, PA9=C_H on TIM1_CH2 — pass high-side channel first (PWM1), low second (PWM2). */
  motor_pwm_set_one_phase(&htim1, TIM_CHANNEL_2, TIM_CHANNEL_1, vc);
}

/**
 * @brief Start six motor PWM channels: slaves first, then TIM1 master.
 *        TIM1 Main Output Enable required for TIM1 pins (advanced timer).
 */
void Motor_PWM_SyncStart(void)
{
  Motor_PWM_SetPhaseVoltagePU(0.0f, 0.0f, 0.0f);
  HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_2);
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_2);
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_2);
  __HAL_TIM_CLEAR_FLAG(&htim1, TIM_FLAG_BREAK);
  __HAL_TIM_MOE_ENABLE(&htim1);
  __HAL_TIM_ENABLE_IT(&htim1, TIM_IT_UPDATE);
}

