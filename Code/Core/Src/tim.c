static float motor_pwm_clamp_duty(float d)
{
  if (d < 0.02f)
  {
    return 0.02f;
  }
  if (d > 0.98f)
  {
    return 0.98f;
  }
  return d;
}

static void motor_pwm_set_one_phase(TIM_HandleTypeDef *htim, uint32_t ch_high, uint32_t ch_low, float v_pu)
{
  float arr_f = (float)__HAL_TIM_GET_AUTORELOAD(htim);
  uint32_t arr = (uint32_t)arr_f;
  float duty = motor_pwm_clamp_duty(0.5f + 0.5f * v_pu);
  uint32_t ccr = (uint32_t)(duty * arr_f + 0.5f);
  if (ccr > arr)
  {
    ccr = arr;
  }
  /* High = PWM1, low = PWM2 (Cube init): same CCR gives complementary OCxREF, not ARR-ccr on two PWM1s (that overlaps both on). */
  __HAL_TIM_SET_COMPARE(htim, ch_high, ccr);
  __HAL_TIM_SET_COMPARE(htim, ch_low, ccr);
}

